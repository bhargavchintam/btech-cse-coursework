#include<stdio.h>

/* truth tables for f = AB + A'C and g = AB + AC + BC (majority),
   rows generated by counting 0..7, A is the msb */

int main()
{
    int m, a, b, c, f, g, i;
    int fm[8], gm[8], nf = 0, ng = 0;

    printf(" m  A B C | f = AB+A'C  g = AB+AC+BC\n");
    printf("----------+--------------------------\n");
    for(m = 0; m < 8; m++)
    {
        a = (m >> 2) & 1;
        b = (m >> 1) & 1;
        c = m & 1;
        f = (a & b) | ((!a) & c);
        g = (a & b) | (a & c) | (b & c);
        printf(" %d  %d %d %d |     %d            %d\n", m, a, b, c, f, g);
        if(f) fm[nf++] = m;
        if(g) gm[ng++] = m;
    }

    printf("\nf = AB + A'C    = Sm(");
    for(i = 0; i < nf; i++)
        printf(i ? ",%d" : "%d", fm[i]);
    printf(")\n");

    printf("g = AB + AC + BC = Sm(");
    for(i = 0; i < ng; i++)
        printf(i ? ",%d" : "%d", gm[i]);
    printf(")\n");

    return 0;
}

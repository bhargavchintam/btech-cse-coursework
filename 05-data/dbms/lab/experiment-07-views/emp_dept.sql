-- canonical teaching schema (emp/dept) - use these EXACT rows in every unit that
-- needs sample data, so query results are consistent across the whole repo.
DROP TABLE IF EXISTS emp;
DROP TABLE IF EXISTS dept;

CREATE TABLE dept (
    deptno INT PRIMARY KEY,
    dname  VARCHAR(20),
    loc    VARCHAR(20)
);

CREATE TABLE emp (
    empno    INT PRIMARY KEY,
    ename    VARCHAR(20),
    job      VARCHAR(15),
    mgr      INT,
    hiredate DATE,
    sal      DECIMAL(8,2),
    comm     DECIMAL(8,2),
    deptno   INT,
    FOREIGN KEY (deptno) REFERENCES dept(deptno)
);

